async function run() {
  console.log('Loading chhathData.ts...');
  const filePath = path.resolve(process.cwd(), 'src/data/chhathData.ts');
  let content = fs.readFileSync(filePath, 'utf8');

  let updatedCount = 0;
  const updatedIds: string[] = [];

  for (const song of CHHATH_SONGS) {
    const newLyrics = LYRICS_DATABASE[song.id];
    if (newLyrics) {
      // Find where this song is in chhathData.ts and inject lyrics field if missing or update it
      // Let's check regex for song id
      const idPattern = new RegExp(`id:\\s*['"]${song.id}['"]([\\s\\S]*?)(?=id:|export const CHHATH_CATEGORIES|$)`);
      const match = content.match(idPattern);
      if (match) {
        let songBlock = match[0];
        const lyricsEscaped = JSON.stringify(newLyrics);
        if (songBlock.includes('lyrics:')) {
          songBlock = songBlock.replace(/lyrics:\s*`[\s\S]*?`|lyrics:\s*"[\s\S]*?"|lyrics:\s*'.*?'/, `lyrics: ${lyricsEscaped}`);
        } else {
          // insert lyrics right before tag: or category: or meaning:
          if (songBlock.includes('meaning:')) {
            songBlock = songBlock.replace('meaning:', `lyrics: ${lyricsEscaped},\n    meaning:`);
          } else if (songBlock.includes('tag:')) {
            songBlock = songBlock.replace('tag:', `lyrics: ${lyricsEscaped},\n    tag:`);
          }
        }
        content = content.replace(match[0], songBlock);
        updatedCount++;
        updatedIds.push(song.id);
      }
    }
  }

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`Successfully updated lyrics for ${updatedCount} songs in src/data/chhathData.ts!`);

  // Now reload and count total with lyrics
  const afterContent = fs.readFileSync(filePath, 'utf8');
  // Check rest songs
  console.log('Check finished.');
}

run().catch(console.error);
